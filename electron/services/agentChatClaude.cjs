const fs = require('fs');
const path = require('path');

function claudeTranscriptPath({ home, cwd, uuid }) {
  if (!uuid) return null;
  const realCwd = fs.realpathSync(cwd);
  const encodedCwd = realCwd.replace(/[^A-Za-z0-9]/g, '-');
  return path.join(home, '.claude', 'projects', encodedCwd, `${uuid}.jsonl`);
}

// User records that are the harness talking to itself, not the user: the
// tags and prose openings Claude Code injects as user turns (after Orca's
// harness-injected-user-turns.ts). Matched case-insensitively on the start.
const USER_NOISE_PREFIXES = [
  '<agent-message',
  '<bash-input>',
  '<bash-stderr>',
  '<bash-stdout>',
  '<command-args>',
  '<command-message>',
  '<command-name>',
  '<cross-session-message',
  '<local-command-caveat>',
  '<local-command-stderr>',
  '<local-command-stdout>',
  '<mcp-polling-update',
  '<mcp-resource-update',
  '<system-reminder>',
  '<task-notification>',
  '<teammate-message',
  '<user-memory-input>',
  '<user-prompt-submit-hook>',
  '<channel source=',
  '[request interrupted',
  'caveat: the messages below were generated by the user while running local commands',
  'this session is being continued from a previous conversation',
];

function isHarnessTurn(text) {
  const head = text.slice(0, 256).toLowerCase();
  return USER_NOISE_PREFIXES.some((p) => head.startsWith(p));
}

// A tool_result's content is a string or an array of text/image blocks.
function toolResultText(content) {
  if (typeof content === 'string') return content;
  if (!Array.isArray(content)) return '';
  return content
    .filter((b) => b.type === 'text' && typeof b.text === 'string')
    .map((b) => b.text)
    .join('\n');
}

// Images stay in the transcript: rows carry where to find one (the record's
// uuid and the block's position inside message.content), and the main
// process serves it from there. No base64 and no file path crosses IPC.
function imageRefs(blocks, uuid, prefix = []) {
  if (!Array.isArray(blocks) || !uuid) return [];
  const refs = [];
  blocks.forEach((b, i) => {
    if (b?.type === 'image') refs.push({ uuid, path: [...prefix, i] });
  });
  return refs;
}

// Background work a tool call started or stopped, from its result. A task
// starts running; a <task-notification> or TaskStop later moves it on.
function noteTask(toolBlock, result, facts) {
  const meta = result.meta || {};
  const input = toolBlock.input || {};
  let started = null;
  if (toolBlock.name === 'Bash' && input.run_in_background && meta.backgroundTaskId) {
    started = { id: meta.backgroundTaskId, command: input.command ?? '' };
  } else if (toolBlock.name === 'Monitor' && meta.taskId) {
    started = { id: meta.taskId, command: input.description || input.command || '' };
  }
  if (started) {
    toolBlock.taskId = started.id;
    facts.tasks[started.id] = facts.tasks[started.id] || {
      ...started,
      status: 'running',
    };
  }
  if (toolBlock.name === 'TaskStop') {
    const task = facts.tasks[meta.task_id || input.task_id];
    if (task) task.status = 'stopped';
  }
}

// <task-notification><task-id>…</task-id>…<status>completed</status>…
// Orca's parser (claude-task-notification-text.ts): the status is read only
// before <summary>, since the <result> a subagent returns can quote its own
// <status> tag.
const TASK_NOTIFICATION_MARKER = '<task-notification>';

function readTaskNotification(text) {
  if (typeof text !== 'string') return null;
  const body = text.trimStart();
  if (!body.startsWith(TASK_NOTIFICATION_MARKER)) return null;
  const taskId = /<task-id>([^<]+)<\/task-id>/.exec(body)?.[1]?.trim();
  if (!taskId) return null;
  const summaryAt = body.indexOf('<summary>');
  const head = summaryAt === -1 ? body : body.slice(0, summaryAt);
  const status = /<status>([a-z_]+)<\/status>/.exec(head)?.[1];
  return status ? { taskId, status } : { taskId };
}

// A background Bash / Monitor task moves on; a background subagent's id is
// its agentId, so its last reported status lands in `facts.agents` — what
// the engine settles an async subagent's row with.
function noteTaskNotification(text, facts) {
  const note = readTaskNotification(text);
  if (!note?.status) return;
  if (facts.tasks[note.taskId]) facts.tasks[note.taskId].status = note.status;
  facts.agents = facts.agents || {};
  facts.agents[note.taskId] = note.status;
}

// The to-do checklist. Older Claude Code rewrites the whole list with
// TodoWrite; current versions (verified on 2.1.x transcripts) keep tasks with
// TaskCreate — whose id only comes back on its result — and TaskUpdate.
// Both fold into the one snapshot the composer pins.
const TODO_STATUSES = new Set(['pending', 'in_progress', 'completed']);

function todoSnapshot(facts) {
  return facts.taskList.order
    .map((id) => facts.taskList.byId[id])
    .filter(Boolean)
    .map((t) => ({ content: t.content, status: t.status }));
}

function noteTodo(toolBlock, result, facts) {
  if (result.is_error) return;
  const input = toolBlock.input || {};
  const list = facts.taskList;
  if (toolBlock.name === 'TaskCreate') {
    const id = result.meta?.createdTaskId;
    if (!id || typeof input.subject !== 'string') return;
    if (!list.byId[id]) list.order.push(id);
    list.byId[id] = { content: input.subject, status: 'pending' };
  } else if (toolBlock.name === 'TaskUpdate') {
    const task = list.byId[String(input.taskId)];
    if (!task) return;
    if (input.status === 'deleted') {
      delete list.byId[String(input.taskId)];
      list.order = list.order.filter((id) => id !== String(input.taskId));
    } else {
      if (TODO_STATUSES.has(input.status)) task.status = input.status;
      if (typeof input.subject === 'string' && input.subject)
        task.content = input.subject;
    }
  } else {
    return;
  }
  facts.todos = todoSnapshot(facts);
}

// Attachment records the chat reads facts from, never rows. A background
// task's completion lands here when Claude absorbs it mid-turn (a queued
// <task-notification>), and running tasks report a task_status.
function noteAttachment(attachment, facts) {
  if (!attachment || typeof attachment !== 'object') return;
  if (
    attachment.type === 'queued_command' &&
    typeof attachment.prompt === 'string' &&
    attachment.prompt.trimStart().startsWith(TASK_NOTIFICATION_MARKER)
  ) {
    noteTaskNotification(attachment.prompt, facts);
  } else if (attachment.type === 'task_status' && attachment.taskId) {
    const task = facts.tasks[attachment.taskId];
    if (task && typeof attachment.status === 'string') task.status = attachment.status;
  }
}

// The inline diff a file-editing tool call carries, or null. Claude Code's
// Edit / Write / MultiEdit inputs; MultiEdit's hunks are shown as one diff.
function editFor(block) {
  const input = block.input || {};
  if (typeof input.file_path !== 'string') return null;
  if (block.name === 'Edit') {
    return {
      path: input.file_path,
      original: input.old_string ?? '',
      modified: input.new_string ?? '',
    };
  }
  if (block.name === 'Write') {
    return { path: input.file_path, original: '', modified: input.content ?? '' };
  }
  if (block.name === 'MultiEdit' && Array.isArray(input.edits)) {
    return {
      path: input.file_path,
      original: input.edits.map((e) => e.old_string ?? '').join('\n\n'),
      modified: input.edits.map((e) => e.new_string ?? '').join('\n\n'),
    };
  }
  return null;
}

// Attach results to their calls and re-emit each call's tool row. A result
// whose call is on a page not loaded yet becomes an orphan row until the call
// shows up.
function attachToolResults(results, record, state) {
  const out = [];
  const tur = record.toolUseResult || {};
  for (const [b, index] of results) {
    const toolUseId = b.tool_use_id;
    const resultBlock = {
      type: 'tool_result',
      content: toolResultText(b.content),
      tool_use_id: toolUseId,
      is_error: !!b.is_error,
      images: imageRefs(b.content, record.uuid, [index]),
      // AskUserQuestion records the chosen labels, keyed by question text.
      answers:
        tur.answers && typeof tur.answers === 'object' && !Array.isArray(tur.answers)
          ? tur.answers
          : undefined,
      // Only the ids background work is tracked by, not the whole result.
      meta: {
        backgroundTaskId: tur.backgroundTaskId,
        taskId: tur.taskId,
        task_id: tur.task_id,
        // A background (async) Agent call returns at once; the subagent
        // keeps running until a <task-notification> names its agentId.
        agentId: typeof tur.agentId === 'string' ? tur.agentId : undefined,
        asyncLaunched: tur.status === 'async_launched' || undefined,
        createdTaskId:
          tur.task && typeof tur.task === 'object' && tur.task.id != null
            ? String(tur.task.id)
            : undefined,
      },
    };
    const callRowId = state.calls[toolUseId];
    const callRow = callRowId && state[callRowId];
    const toolBlock = callRow?.blocks.find(
      (x) => x.type === 'tool_use' && x.id === toolUseId
    );
    if (toolBlock) {
      toolBlock.result = resultBlock;
      noteTask(toolBlock, resultBlock, state.facts);
      noteTodo(toolBlock, resultBlock, state.facts);
      out.push({
        id: toolBlock.rowId,
        role: 'tool',
        tool_use: toolBlock,
        result: resultBlock,
        edit: editFor(toolBlock),
        taskId: toolBlock.taskId,
      });
    } else {
      const orphanRowId = record.uuid || `orphan-${toolUseId}`;
      state.results[toolUseId] = { ...resultBlock, rowId: orphanRowId };
      out.push({
        id: orphanRowId,
        role: 'user',
        orphan: true,
        blocks: [resultBlock],
      });
    }
  }
  if (out.length === 0) return null;
  return out.length === 1 ? out[0] : out;
}

function decodeClaudeLine(lineStr, state) {
  if (!lineStr.trim()) return null;
  let record;
  try {
    record = JSON.parse(lineStr);
  } catch {
    return null;
  }
  const rows = decodeRecord(record, state);
  // Every timestamped record moves the clock a later thinking block measures
  // its duration from.
  const ts = Date.parse(record.timestamp);
  if (Number.isFinite(ts)) state.lastTs = ts;
  return rows;
}

function decodeRecord(record, state) {
  state.facts = state.facts || { tasks: {}, todos: null, usage: null };
  state.facts.taskList = state.facts.taskList || { order: [], byId: {} };
  if (record.type === 'attachment') {
    noteAttachment(record.attachment, state.facts);
    return null;
  }

  const skipTypes = [
    'attachment',
    'file-history-snapshot',
    'file-history-delta',
    'last-prompt',
    'mode',
    'permission-mode',
    'queue-operation',
    'system',
  ];
  if (skipTypes.includes(record.type)) return null;
  if (record.isMeta || record.isSynthetic || record.isCompactSummary) return null;

  state.calls = state.calls || {};
  state.results = state.results || {};

  // Claude names the conversation in its own record, and renames it later.
  if (record.type === 'ai-title') {
    return typeof record.aiTitle === 'string' && record.aiTitle.trim()
      ? { isHeader: true, title: record.aiTitle.trim() }
      : null;
  }

  if (record.type === 'user') {
    // The turn lives under message.content: a string, or an array of blocks.
    const content = record.message?.content;
    const blocks =
      typeof content === 'string' ? [{ type: 'text', text: content }] : content;
    if (!Array.isArray(blocks)) return null;

    // Tool results arrive as user records of tool_result blocks, keyed by
    // tool_use_id. They attach to their call, never show as a user message.
    const results = blocks
      .map((b, i) => [b, i])
      .filter(([b]) => b.type === 'tool_result');
    if (results.length > 0) return attachToolResults(results, record, state);

    const contentStr = blocks
      .filter((b) => b.type === 'text' && typeof b.text === 'string')
      .map((b) => b.text)
      .join('\n')
      .trim();
    if (contentStr.startsWith(TASK_NOTIFICATION_MARKER)) {
      noteTaskNotification(contentStr, state.facts);
      return null;
    }
    // Stop's Esc makes Claude record an interrupt notice as a user turn: a
    // quiet status row, never a bubble the user didn't type.
    if (record.interruptedMessageId || /^\[request interrupted/i.test(contentStr)) {
      return record.uuid
        ? { id: record.uuid, role: 'status', content: 'Interrupted' }
        : null;
    }
    if (isHarnessTurn(contentStr)) return null;
    const images = imageRefs(blocks, record.uuid);
    if (!contentStr && images.length === 0) return null;

    return {
      id: record.uuid,
      role: 'user',
      content: contentStr,
      images,
    };
  }

  if (record.type === 'assistant') {
    // Context in use = everything the last request read plus what it wrote.
    const u = record.message?.usage;
    if (u && record.message.model && record.message.model !== '<synthetic>') {
      state.facts.usage = {
        model: record.message.model,
        tokens:
          (u.input_tokens || 0) +
          (u.cache_creation_input_tokens || 0) +
          (u.cache_read_input_tokens || 0) +
          (u.output_tokens || 0),
      };
    }
    const id = record.message?.id || record.uuid || Math.random().toString();

    if (!state[id]) {
      state[id] = {
        id,
        role: 'assistant',
        blocks: [],
      };
    }

    // Row ids must survive Load older, which decodes each page with fresh
    // state and so may see only part of a message: a tool call is keyed by
    // its tool_use id, any other block by the record that carries it.
    if (record.message?.content) {
      for (const block of record.message.content) {
        if (block.type !== 'tool_use') continue;
        state.toolUseCount = (state.toolUseCount || 0) + 1;
        if (block.name === 'TodoWrite' && Array.isArray(block.input?.todos)) {
          state.facts.todos = block.input.todos.map((t) => ({
            content: t.content,
            status: t.status,
          }));
        }
      }
      // Claude writes a thinking record once the block is done, so the time
      // it took is the gap since the record before it (the prompt or tool
      // result that started the request). On real transcripts the gap after
      // it is only the next block's own write time, often under a second.
      const ts = Date.parse(record.timestamp);
      const thoughtMs =
        Number.isFinite(ts) && Number.isFinite(state.lastTs) && ts >= state.lastTs
          ? ts - state.lastTs
          : null;
      const tagged = record.message.content.map((b, i) => ({
        ...b,
        rowId: b.type === 'tool_use' ? b.id : `${record.uuid || id}-${i}`,
        ...(b.type === 'thinking' && thoughtMs !== null ? { durationMs: thoughtMs } : {}),
      }));
      state[id].blocks = state[id].blocks.concat(tagged);
    }

    const removeIds = [];
    const rows = [];

    for (const block of state[id].blocks) {
      const blockId = block.rowId;

      if (block.type === 'text') {
        if (block.text) {
          rows.push({ id: blockId, role: 'assistant', content: block.text });
        }
      } else if (block.type === 'tool_use') {
        state.calls[block.id] = id;
        if (!block.result && state.results[block.id]) {
          block.result = state.results[block.id];
          removeIds.push(state.results[block.id].rowId);
          noteTask(block, block.result, state.facts);
          noteTodo(block, block.result, state.facts);
        }

        rows.push({
          id: blockId,
          role: 'tool',
          tool_use: block,
          result: block.result,
          edit: editFor(block),
          taskId: block.taskId,
        });
      } else if (block.type === 'thinking') {
        rows.push({
          id: blockId,
          role: 'reasoning',
          content: block.thinking,
          durationMs: block.durationMs ?? null,
        });
      }
    }

    if (removeIds.length > 0 && rows.length > 0) {
      rows[0].remove = removeIds;
    }

    return rows;
  }

  return null;
}

// The full text of one tool result, for "Show full output": a user record's
// tool_result block keyed by tool_use_id.
function findToolResult(record, toolUseId) {
  if (record?.type !== 'user' || !Array.isArray(record.message?.content)) return null;
  const block = record.message.content.find(
    (b) => b?.type === 'tool_result' && b.tool_use_id === toolUseId
  );
  return block ? toolResultText(block.content) : null;
}

