#!/usr/bin/env node

// Packs xterm.js and its Unicode 11 addon into string constants the
// terminal WebView document inlines (after Orca's
// mobile/scripts/build-terminal-webview-engine.mjs). The document used to
// load both from jsDelivr with no integrity check — and the page it builds
// is the one that receives every decrypted byte of terminal output, so a
// CDN (or anyone on the phone's path to it) could read it. Bundled, the
// WebView loads nothing from the network at all.
//
// Runs on postinstall, so `npm ci` always leaves a fresh copy; the output is
// gitignored. Versions come from mobile/package.json, pinned to the
// desktop's (terminalWebView.test.ts checks they stay equal).

import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as esbuild from 'esbuild';

const require = createRequire(import.meta.url);
const mobileRoot = join(dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = join(mobileRoot, 'src', 'terminal', 'terminalEngine.generated.ts');
// Old Android System WebViews are Chromium-based; this keeps the syntax
// they can parse.
const target = 'chrome74';

async function version(name) {
  return JSON.parse(await readFile(require.resolve(`${name}/package.json`), 'utf8')).version;
}

// A literal </script> or </style> inside the inlined text would end the
// element early.
function htmlText(value, tag) {
  return value.replace(new RegExp(`</${tag}`, 'gi'), `<\\/${tag}`);
}

async function buildEngineJs() {
  const result = await esbuild.build({
    stdin: {
      contents: `
        import { Terminal } from '@xterm/xterm';
        import { Unicode11Addon } from '@xterm/addon-unicode11';
        window.Terminal = Terminal;
        window.Unicode11Addon = { Unicode11Addon };
      `,
      resolveDir: mobileRoot,
      sourcefile: 'terminal-engine-entry.js',
    },
    bundle: true,
    format: 'iife',
    minifyWhitespace: true,
    minifyIdentifiers: true,
    minifySyntax: false,
    platform: 'browser',
    target,
    legalComments: 'none',
    write: false,
    logLevel: 'silent',
  });
  return result.outputFiles[0].text;
}

const [js, rawCss, xterm, unicode11] = await Promise.all([
  buildEngineJs(),
  readFile(require.resolve('@xterm/xterm/css/xterm.css'), 'utf8'),
  version('@xterm/xterm'),
  version('@xterm/addon-unicode11'),
]);
// Comments carry the upstream URLs; the SVG namespace in data URLs is
// percent-encoded so the document holds no http(s) URL at all (nothing is
// fetched either way — SVG parsing decodes it).
const css = rawCss
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .replace(/http:\/\/www\.w3\.org\/2000\/svg/g, 'http%3A//www.w3.org/2000/svg');

await writeFile(
  outputPath,
  [
    '// Generated by scripts/build-terminal-engine.mjs (postinstall). Do not edit.',
    `// @xterm/xterm@${xterm}, @xterm/addon-unicode11@${unicode11}, target ${target}.`,
    '/* eslint-disable */',
    `export const XTERM_ENGINE_VERSIONS = ${JSON.stringify({ xterm, unicode11 })};`,
    `export const XTERM_ENGINE_JS = ${JSON.stringify(htmlText(js, 'script'))};`,
    `export const XTERM_ENGINE_CSS = ${JSON.stringify(htmlText(css, 'style'))};`,
    '',
  ].join('\n')
);
console.log(`terminal engine: ${outputPath} (${Math.round((js.length + css.length) / 1024)} KiB)`);
